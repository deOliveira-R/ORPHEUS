# ── Cylindrical tests ──────────────────────────────────────────────


@pytest.mark.l0
@pytest.mark.verifies("hebert-3-432")
@pytest.mark.catches("ERR-048")
@pytest.mark.parametrize("n_cells", [20, 40, 80])
@pytest.mark.parametrize("n_mu", [4, 8])
@pytest.mark.parametrize("inner_solver", ["source_iteration", "krylov"])
def test_homogeneous_streaming_equilibrium_cylinder(
    n_cells: int, n_mu: int, inner_solver: str,
) -> None:
    r"""Homogeneous reflective cylinder → analytical streaming equilibrium.

    Cylindrical analog of the spherical test above.  Uses the folded
    product quadrature (GL polar levels × the σ_y-quotiented staggered
    azimuthal arc) — the carrying family SNMesh(CYLINDRICAL) admits,
    with the M-M per-level azimuthal redistribution sweep marching the
    ψ½ system directly (Q5.6.3).

    Both inner solvers must converge to ψ_n = φ/Σw at every cell.
    Coverage: n_mu ∈ {4, 8} polar × parent n_phi = 4 azimuth (8 / 16
    folded ordinates) × 3 mesh sizes × 2 inner solvers = 12 cases.
    Larger ordinate counts add minutes per Krylov solve and provide no
    additional information against the analytical limit.
    """
    fuel = get_mixture("B", "1g")
    geom = StructuredGeometry(
        geometry="CYL",
        regions=(Region(mat_id=0, outer_thickness_cm=_R_CYL),),
        bcs=(BC.reflective,),
    )
    mesh = Mesh1D.from_geometry(
        geom, region_meshes=(RegionMesh(n_cells=n_cells),),
    )
    quad = Quadrature.folded_product(n_mu=n_mu, n_phi=4)
    N = quad.N
    nx = mesh.N
    ng = 1
    # R-1 Step 4 A1 — per-ordinate density (1 / sum_w).
    sum_w = float(np.sum(quad.weights))
    Q = np.full((N, ng, nx), 1.0 / sum_w)

    result = solve_sn_fixed_source(
        materials={0: fuel}, mesh=mesh, quadrature=quad, external_source=Q,
        boundary_condition="reflective", inner_solver=inner_solver,
    )
    # D-H.1d: Solution.angular_flux is TimedFullField.
    psi = result.angular_flux.interior.values   # (N, ng, nx)
    sf = result.scalar_flux.values          # (ng, nx)

    psi_expected = _expected_psi(quad)
    phi_expected = _expected_phi()

    np.testing.assert_allclose(
        psi, psi_expected, rtol=1e-9,
        err_msg=(
            f"Per-ordinate ψ deviates from Pomraning isotropy "
            f"(expected {psi_expected:.6f} = {phi_expected}/Σw).  "
            f"Configuration: cylinder, n_cells={n_cells}, n_mu={n_mu}, "
            f"inner_solver={inner_solver}."
        ),
    )
    np.testing.assert_allclose(
        sf, phi_expected, rtol=1e-9,
        err_msg=(
            f"Scalar flux deviates from streaming-equilibrium analytical "
            f"limit φ = {phi_expected}.  Configuration: cylinder, "
            f"n_cells={n_cells}, n_mu={n_mu}, "
            f"inner_solver={inner_solver}."
        ),
    )


# ── Pomraning per-ordinate isotropy at the pole ────────────────────


@pytest.mark.l0
@pytest.mark.verifies("hebert-3-432")
@pytest.mark.catches("ERR-048")
@pytest.mark.parametrize("inner_solver", ["source_iteration", "krylov"])
def test_pomraning_pole_isotropy_sphere(inner_solver: str) -> None:
    r"""Per-ordinate cv at the pole must be ≤ 0.01 on flat-flux input.

    Pomraning 1989 NSE 102:317-336: at the spherical pole r = 0 the
    angular flux must be isotropic because the curvilinear angular
    redistribution operator is singular there.  On a homogeneous
    reflective sphere with isotropic source, this isotropy propagates
    to all r via symmetry — ψ_n(r) = φ(r)/Σw, independent of n.

    A pre-Phase-G-Step-2 buggy SI sweep had cv(ψ@i=0) ≈ 0.52 on
    mixture B; this gate pins cv ≤ 0.01.
    """
    fuel = get_mixture("B", "1g")
    geom = StructuredGeometry(
        geometry="SPH",
        regions=(Region(mat_id=0, outer_thickness_cm=_R_SPHERE),),
        bcs=(BC.reflective,),
    )
    mesh = Mesh1D.from_geometry(geom, region_meshes=(RegionMesh(n_cells=40),))
    quad = Quadrature.gauss_legendre(n_ordinates=8)
    N = quad.N
    nx = mesh.N
    ng = 1
    # R-1 Step 4 A1 — per-ordinate density (1 / sum_w).
    sum_w = float(np.sum(quad.weights))
    Q = np.full((N, ng, nx), 1.0 / sum_w)

    result = solve_sn_fixed_source(
        materials={0: fuel}, mesh=mesh, quadrature=quad, external_source=Q,
        boundary_condition="reflective", inner_solver=inner_solver,
    )
    # D-H.1d: Solution.angular_flux is TimedFullField.
    psi_at_pole = result.angular_flux.interior.values[:, 0, 0]   # (N,)
    cv = float(np.std(psi_at_pole) / np.mean(psi_at_pole))
    assert cv < 0.01, (
        f"Pomraning pole isotropy violated for {inner_solver}: "
        f"cv(ψ@i=0) = {cv:.4e}, max = {psi_at_pole.max():.6f}, "
        f"min = {psi_at_pole.min():.6f}.  Pre-Phase-G-Step-2 SI "
        f"showed cv ≈ 0.52; the gate is 0.01."
    )
