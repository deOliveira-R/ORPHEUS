def _template_fds(pid: int) -> int:
    return len(subprocess.run(["lsof", "-p", str(pid)], capture_output=True, text=True).stdout.splitlines())


def _zombies_of(pid: int) -> int:
    rows = subprocess.run(["ps", "-A", "-o", "ppid=,stat="], capture_output=True, text=True).stdout.splitlines()
    return sum(1 for row in rows if row.split() and row.split()[0] == str(pid) and row.split()[1].startswith("Z"))


