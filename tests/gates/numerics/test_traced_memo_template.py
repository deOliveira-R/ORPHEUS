def test_a_probe_and_a_listing_are_observed_when_the_run_made_them(make, tmp_path, monkeypatch, route, case):
    """qa's third review, F2: a presence probe and a directory listing are pinned by what the run SAW, at its
    first touch, like an opened file (qa2). The generator probes a path (or lists a directory), signals that it
    has (a file it writes itself, its own output), and sleeps; meanwhile the path is created (or an entry added).
    The entry is born stale: the call raises "does not validate" and the lookup is ``Stale``, never a ``Hit``
    serving what the run saw under what came after. The generator's own signal makes the row discriminate on
    the forked route too (a fixed delay from the call is outrun by a template's start). First reds: probes
    observed after the run (``presence``, battery H arm H-2); listings observed after the run (``listing``, arm
    H-3)."""
    _route(monkeypatch, route)
    directory, ready = tmp_path / "files", tmp_path / "ready"
    directory.mkdir()
    (directory / "listed").mkdir()
    m = make(m=_OBSERVED_THEN_CHANGED.format(directory=str(directory), ready=str(ready))).module()
    function, argument = (m.presence_then_wait, "flag") if case == "presence" else (m.listing_then_wait, "listed")
    outcome: list[object] = []

    def call() -> None:
        try:
            outcome.append(function(argument))
        except Exception as error:  # noqa: BLE001 - the outcome is asserted below
            outcome.append(error)

