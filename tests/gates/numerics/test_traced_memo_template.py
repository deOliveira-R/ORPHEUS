# ── E5: one OS thread at the fork ────────────────────────────────────────────────────────────────────


@needs_fork
def test_e5_the_thread_counter_sees_native_threads_and_a_second_thread_refuses_the_fork():
    """E5: the template's counter (``FORK_MEASURED[fork_platform()]``, the libproc thread counter) reads 1 in a fresh single-threaded process, 2 with a started
    ``threading.Thread`` (a thread ``threading`` itself would count), and more than 1 after a BLAS call (native
    threads, which ``threading.active_count`` reads as 1). ``_fork_unsafe`` refuses to fork with a count of 2. A
    fork with more than one thread crashed 20 of 20 children (``ta/fork``). First red: a counter blind to native
    threads, or a template that does not ask it."""
    probe = textwrap.dedent('''
        import threading, numpy as np
        from orpheus.numerics import _traced_memo_boot as boot
        from orpheus.numerics import traced_memo as tm
        count = boot.FORK_MEASURED[tm.fork_platform()]()
        a = count()
        e = threading.Event(); t = threading.Thread(target=e.wait); t.start(); b = count(); e.set(); t.join()
        _ = np.ones((1500, 1500)) @ np.ones((1500, 1500))
        print(a, b, count(), threading.active_count(), "|", repr(boot._fork_unsafe(lambda: 2)), "|", repr(boot._fork_unsafe(lambda: 1)))
    ''')
    env = {k: v for k, v in os.environ.items() if k not in ("OMP_NUM_THREADS", "VECLIB_MAXIMUM_THREADS")}
    run = subprocess.run([sys.executable, "-O", "-c", probe], cwd=REPO, capture_output=True, text=True, env=env)
    assert run.returncode == 0, run.stderr[-2000:]
    counts, refused, allowed = run.stdout.split("|")
    a, b, c, active = (int(v) for v in counts.split())
    assert (a, b) == (1, 2) and c > 1 and active == 1, run.stdout
    assert refused.strip() == "('2 OS threads',)" and allowed.strip() == "()", run.stdout


