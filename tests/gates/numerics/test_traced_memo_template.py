@needs_fork
@pytest.mark.timeout(120)
@pytest.mark.rests_on('tests/gates/numerics/test_traced_memo_template.py::test_e7a_a_template_ends_when_the_process_that_started_it_is_killed')
def test_a_fork_of_the_asking_process_does_not_keep_its_template_alive(make):
    """The elegance review's P3: a child forked from a process that holds a template closes its copies of the
    template's pipes (``_SLOT.forget`` at fork), so when the parent releases its own ends the template reaches
    the end of its input and exits while the child still runs. First red (battery I arm I-4): ``forget()``
    resetting the slot without releasing, so the child's copy of the template's stdin holds it open."""
    memo = _memo()
    m = make(m=GENERATOR).module()
    m.generate(1.0)
    template = memo._SLOT.template
    child = os.fork()
    if child == 0:
        time.sleep(8.0)
        os._exit(0)
    try:
        template.release()
        memo._SLOT.template = None
        deadline = time.monotonic() + 4.0
        while template.process.poll() is None and time.monotonic() < deadline:
            time.sleep(0.05)
        ended = template.process.poll() is not None
        child_running = os.waitpid(child, os.WNOHANG) == (0, 0)
    finally:
        if template.process.poll() is None:
            template.process.kill()
            template.process.wait()
        os.kill(child, signal.SIGKILL)
        os.waitpid(child, 0)
    assert child_running, "the child ended first: the row observed nothing"
    assert ended, "the template outlived its parent's release while a forked child held its stdin"
