_E3_DRIVER = '''
import sys
sys.path[:0] = [{tree!r}]
import orpheus
assert orpheus.__file__.startswith({tree!r}), orpheus.__file__
from pathlib import Path
from orpheus.numerics import traced_memo as tm
import e3_fixture.m as m
assert tm._forks_here()
content = Path({tree!r}) / "orpheus" / "numerics" / "content.py"
with tm.cache_root({cache!r}):
    first = m.read_probe(1.0)
    pid = tm._SLOT.template.process.pid
    text = content.read_text()
    content.write_text(text.replace({old!r}, {new!r}))
    second = m.read_probe(2.0)
    print("FIRST", first, "SECOND", second, "SAME_TEMPLATE", tm._SLOT.template.process.pid == pid,
          "VERDICT", type(m.read_probe.lookup(2.0)).__name__)
'''

_E3_PROBE = '''

E3_CONSTANT = 1.0


def e3_probe(x):
    """Defined in a module the template imports, and never run by its import."""
    return x * 10.0 + E3_CONSTANT
'''


@needs_fork
@pytest.mark.parametrize("old,new,expected", [("return x * 10.0 + E3_CONSTANT", "return x * 20.0 + E3_CONSTANT", 41.0),
                                              ("E3_CONSTANT = 1.0", "E3_CONSTANT = 5.0", 25.0)],
                         ids=["def-body-never-run-by-the-import", "module-constant"])
@pytest.mark.rests_on(_E1)
def test_e3_an_edit_to_a_module_the_template_imported_is_run_new(tmp_path, old, new, expected):
    """E3: on a copy of the package's Python files (the memo under test is the copy's), a template starts at the
    first miss; then a module the TEMPLATE imported is edited: a def body its import never ran (so no import-time
    pin covers it), or a module constant. The next miss returns the answer of the NEW code, from another template
    (the first one refused to fork), and its entry validates. First red: a template that does not re-check the
    bytes it compiled, which forks the old code under the new bytes' pins: a stale entry that validates."""
    tree = tmp_path / "tree"
    shutil.copytree(REPO / "orpheus", tree / "orpheus",
                    ignore=lambda d, names: [n for n in names if n == "__pycache__" or (not n.endswith(".py") and not (Path(d) / n).is_dir())])
    content = tree / "orpheus" / "numerics" / "content.py"
    content.write_text(content.read_text() + _E3_PROBE)
    (tree / "e3_fixture").mkdir()
    (tree / "e3_fixture" / "__init__.py").write_text("")
    (tree / "e3_fixture" / "m.py").write_text(textwrap.dedent('''
        from orpheus.numerics import content
        from orpheus.numerics.traced_memo import traced_memo


        @traced_memo
        def read_probe(x: float) -> float:
            return content.e3_probe(x)
    '''))
    driver = tmp_path / "driver.py"
    driver.write_text(_E3_DRIVER.format(tree=str(tree), cache=str(tmp_path / "cache"), old=old, new=new))
    run = subprocess.run([sys.executable, *(["-O"] if sys.flags.optimize else []), str(driver)], cwd=tmp_path,
                         capture_output=True, text=True, timeout=300)
    assert run.returncode == 0, run.stderr[-3000:]
    words = run.stdout.split()
    first, second = float(words[words.index("FIRST") + 1]), float(words[words.index("SECOND") + 1])
    assert first == 11.0, first
    assert second == expected, f"the template ran the code it imported before the edit: {second}, new code gives {expected}"
    assert words[words.index("SAME_TEMPLATE") + 1] == "False", "the template that compiled the old code forked again"
    assert words[words.index("VERDICT") + 1] == "Hit"


