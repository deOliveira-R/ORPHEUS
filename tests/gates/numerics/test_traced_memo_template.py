def _memo():
    return api.module()


def _forks() -> bool:
    return bool(_memo()._forks_here())


needs_fork = pytest.mark.skipif(not _forks(), reason="this platform spawns a fresh interpreter per miss (the scope boundary)")


@pytest.fixture
def make(tmp_path):
    """Generator packages under ``tmp_path`` and a store of the row's own, with no template from an earlier row."""
    _memo()._SLOT.close()
    made: list[_Package] = []

    def build(**modules: str) -> _Package:
        made.append(_Package(tmp_path, **modules))
        return made[-1]

    with api.cache_root(tmp_path / "cache"):
        yield build
    for package in made:
        package.close()
    _memo()._SLOT.close()


def _forked_calls(monkeypatch) -> list[int]:
    """A list that grows by one each time a miss is answered by a template (the route, observed on it)."""
    memo, calls = _memo(), []
    original = memo._SLOT.answer

    def counting(launch, job):
        calls.append(1)
        return original(launch, job)

    monkeypatch.setattr(memo._SLOT, "answer", counting)
    return calls


#: The memo's own sources. Their pins on a DefPin are the memo's machinery, which the MemoPin already pins by
#: bytes; which of them a manifest holds depends on which process ran it (a template's job loop, a loader that
#: found its bytecode cached or wrote it), so E1 and E8 compare manifests without them, and say so.
_MEMO_FILES = ("orpheus/numerics/traced_memo.py", "orpheus/numerics/_traced_memo_boot.py", "orpheus/numerics/content.py")


def _pins(entry: Path) -> set[tuple]:
    """The entry's pins, less the DefPins on the memo's own sources (covered by its MemoPin)."""
    rows = {tuple([kind, *map(str, fields)]) for kind, *fields in api.read_entry(entry)["manifest"]}
    return {row for row in rows if not (row[0] == "DefPin" and row[1].endswith(_MEMO_FILES))}


# ── E1, E2, E9: what a forked child holds and answers ────────────────────────────────────────────────


@needs_fork
@pytest.mark.rests_on(_M31)
def test_e1_a_forked_childs_manifest_is_a_fresh_processs(make, tmp_path, monkeypatch):
    """E1 and E9: three misses of one generator forked from one template, and the same three generated by fresh
    interpreters (``_forks_here`` off), give the same pin set, entry by entry, and the same payload bits; the
    three forked entries pin the same code (the k-th fork holds what the first held). The DefPins on the memo's
    own sources are left out of the comparison (``_MEMO_FILES``: the MemoPin covers them, and a template's job
    loop runs memo code a fresh process does not). Measured blind arm (``[M]`` 2026-10-16, battery E arm E-a): a
    child that does not restore the snapshot pins the same set, since everything the template ran after the
    snapshot is memo code or the standard library; the restore keeps only the memo's own pins exact. A template
    that runs each job itself before forking (arm E-b) reddens it: its children never run what it warmed."""
    memo = _memo()
    calls = _forked_calls(monkeypatch)
    m = make(m=GENERATOR).module()
    forked = {}
    for x in (1.0, 2.0, 3.0):
        m.generate(x)
        forked[x] = _pins(next(f for f in api.entry_files(tmp_path / "cache") if f.stem == m.generate.key(x)))
    assert len(calls) == 3, f"the misses were not forked: {len(calls)} of 3"
    memo._SLOT.close()
    monkeypatch.setattr(memo, "_forks_here", lambda: False)
    fresh = {}
    with api.cache_root(tmp_path / "fresh"):
        for x in (1.0, 2.0, 3.0):
            m.generate(x)
            fresh[x] = _pins(next(f for f in api.entry_files(tmp_path / "fresh") if f.stem == m.generate.key(x)))
            assert api.read_entry(next(f for f in api.entry_files(tmp_path / "fresh") if f.stem == m.generate.key(x)))["payload_digest"] == \
                api.read_entry(next(f for f in api.entry_files(tmp_path / "cache") if f.stem == m.generate.key(x)))["payload_digest"]
    assert len(calls) == 3
    for x in fresh:
        assert forked[x] == fresh[x], (x, sorted(forked[x] ^ fresh[x])[:6])
    assert forked[1.0] == forked[2.0] == forked[3.0]


