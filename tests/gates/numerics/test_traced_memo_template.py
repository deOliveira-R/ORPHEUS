r"""#602 cut E: each miss forked from a recording template, gated before it may stand in for a fresh interpreter.

Spec ``scratch/characteristic_architecture/p3/m602/round2_gate_spec.md`` §3.2, rows E1–E10, and the platform
boundary. The fork-safety protocol of §3.3 ran 2026-10-16 (``ta/fork/full/driver.log``: 32 400 forks over 9 thread
settings, 0 failures; a template that called BLAS before forking crashed 20 of 20 children).

A template (``_traced_memo_boot.template``) records from its first line, imports the memo as a generating process
does, snapshots its recording, and forks one child per miss; the child restores the snapshot and generates. What
must hold for the child to be the fresh generating process it replaces:

* E1, its manifest is a fresh process's manifest; E2, it holds no earlier generation's memory;
* E3, the template's code is the code on disk (an edit after the template started is never run as old code under
  new pins); E4, no patch of the asking process reaches it;
* E5, the template forks with one OS thread; E6, the state a manifest pins (environment, working directory,
  ``sys.path``) is the asking process's; E7, the template's lifetime; E8, a nested miss; E9, its bits.

Every generator is a synthetic package under ``tmp_path``; E3 edits a COPY of the package's Python files in a
driver process. Rows that start a template from this process close it first, so the template under test is
started inside the row.
"""
