r"""The reference carry: every reference body, re-posed with face roles and an ``exterior``, solves to the HEAD bits (wave 2, S5; plan 6.5 gate 2).

Specified by the test-architect (2026-10-23, ``.claude/plans/wave2_boundary_carve.md`` 6.5). The carve re-poses the reference
specification: a face's typed boundary law becomes a face role (a deck or an integer tag) and the tag's wall becomes an entry of
``exterior``. This gate is the carry for the references, the counterpart of the production carry fixture
(``tests/gates/transport/carry_head.npz``): the SAME declarations, solved by the SAME reference at the SAME resolution, must
return the SAME bits before and after.

**The population, and what "the reference registry" is.** ``orpheus/`` holds no registry that builds a
``GeometrySpecification`` (``[M]`` AST: one definition, 0 construction calls in ``orpheus/``; the 29 constructions are in
``tests/``). The population is therefore stated by this gate: the 19 bodies of
:mod:`tests.gates.derivations._reference_carry_cases`, each solved as the fundamental eigenvalue of a TWO-GROUP,
heterogeneous body (the Sood registry's ``PU_2_0_SL_STUB`` downscatter mixture and ``URRB_2_0_IN`` upscatter mixture alternating by
interval: ``vv-principles`` anti-patterns 3 and 4), over every chart the characteristic reference serves (slab, sphere, cylinder,
hollow sphere, hollow cylinder) and every wall kind it states (vacuum, mirror, partial specular, white, wrap), including both
orderings of a diffuse and a specular wall on one body. That is 19 specifications through the reference's door
(``CharacteristicDerivation``), plus the ``specular_albedos`` of the 12 specular-only bodies, which feeds the three consumers
(``Spectrum``, ``MomentSpace``, ``BasisSpace``).

**The fixture** ``reference_carry_head.json`` was captured ONCE at ``main`` ``5d04c296`` by
:mod:`tests.gates.derivations._capture_reference_carry_head`, from a ``git archive`` extraction outside the repository, the
script printing the extraction's ``orpheus.__file__``; the eigenvalue is held as ``float.hex`` (bit-exact), read in process
(``traced_memo.bypass()``) so no cache entry stands in for a solve (a memo is keyed by content digest, and every digest changes with
this carve, ``R-6``: reading through the memo would MISS and solve anyway, but only a bypass makes the claim independent of
that). The comparison is ``==`` on the hex, never a tolerance: the carve moves no reduction of the reference (the walls it reads
are the same floats and indices, gate 3), so bit-identity is the claim and a non-bit difference is a finding to investigate
(``vv-principles``, bit-identity vs principled equivalence: nothing here is reordered). Resolution
``Resolution(1, 0, 0.4, TransportResolution(8), 8)``, the cheapest the bodies solve at: the claim is identity, not accuracy.

**Independence (X4).** HEAD and the carved tree share the characteristic reference's numerics (that is the point of a carry: the
only thing that changed is how the walls are STATED), so this gate pins the carve and does not verify the reference; the
references' own verification is ``test_characteristic_*`` and the independent-references gate. The walls the two trees read are
compared EXPLICITLY in ``test_walls_of_reads_decks_and_amplitudes.py`` against a hand rule, so a carry that held because both
trees read the wrong wall is caught there, not here.

Rows: the fixture is the population it claims (fast, not red at base); every body's albedos equal HEAD's (fast); every body's
k equals HEAD's bit for bit (``slow``: 19 solves, 70 s measured at HEAD, 2026-10-23, ``[M]`` serial host, sum of the per-body seconds
in the fixture).

Declared red at the base tip (``de354496``): the k rows fail at the Sood registry import (``sood_registry/case.py`` imports the
retired ``BC``, which is where the two-group mixtures come from; past it they would fail at ``GeometrySpecification(...,
exterior=...)``, no such keyword) and the albedo rows at the ``reference_body`` import (``BC``): the base cannot tell the rows' named
reasons apart, which is stated here and is proven by the mutations below on the carved tree. Mutations the reviewers apply to the carved tree: (1) a wall's
amplitudes read from the wrong tag reddens the two-tag bodies' k; (2) the diffuse amplitude read as specular reddens every white
body's k and the slab-white-mirror's; (3) a mirror deck read as vacuum reddens the mirror bodies. The fixture is committed and never regenerated by a test: a regenerating test would carry the carve's own answer.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from tests.gates._content_identity_helpers import require
from tests.gates.derivations import _reference_carry_cases as cases
from tests.gates.derivations import _reference_carry_spelling as spelling

pytestmark = pytest.mark.foundation

_FIXTURE = Path(__file__).resolve().parent / "reference_carry_head.json"
_HERE = "tests/gates/derivations/test_reference_carry.py::"
_WALLS = "tests/gates/derivations/test_walls_of_reads_decks_and_amplitudes.py::"
_BODY_IDS = [c[0] for c in cases.CASES]


def _head() -> dict:
    return json.loads(_FIXTURE.read_text())


def test_the_carry_fixture_is_the_population_it_claims() -> None:
    """19 bodies, each with a k (a refusal at HEAD would be recorded as such: 0 of 19 are), the resolution stated, the specular-only albedos present.

    Not red at base (it reads no production): the instrument's own control. The fixture holds a ``k_hex`` that parses as a float
    for every body and an ``albedos`` list for exactly the ``SPECULAR_ONLY`` ones."""
    head = _head()
    names = [k for k in head if not k.startswith("_")]
    require(sorted(names) == sorted(_BODY_IDS) and len(names) == 19, f"the fixture holds {len(names)} bodies")
    require(head["_resolution"] == {"degree": 1, "layers": 0, "ratio": 0.4, "line_points": 8, "projection_points": 8}, "resolution moved")
    for name in names:
        require("k_hex" in head[name], f"{name}: HEAD refused the solve: {head[name].get('k')}")
        float.fromhex(head[name]["k_hex"])
        require(("albedos" in head[name]) == (name in cases.SPECULAR_ONLY), f"{name}: albedos present iff specular-only")
    require(len(cases.SPECULAR_ONLY) == 12, f"the specular-only population is {len(cases.SPECULAR_ONLY)}, not 12")


def _mixtures() -> dict:
    from orpheus.derivations.continuous.sood_registry import sood2003 as sood

    return {0: sood.PU_2_0_SL_STUB.materials[0], 1: sood.URRB_2_0_IN.materials[0]}


def _k(name: str) -> float:
    from orpheus.data.cells import CellCoefficient, Channel
    from orpheus.data.materials import Materials
    from orpheus.derivations.continuous.characteristic import CharacteristicDerivation, Resolution, TransportResolution
    from orpheus.numerics.observable import Eigenvalue
    from orpheus.numerics.question import Eigen
    from orpheus.numerics.traced_memo import bypass
    from orpheus.specification.specification import GeometrySpecification

    _n, chart, bp, faces = next(c for c in cases.CASES if c[0] == name)
    geometry, exterior = spelling.geometry_and_exterior(chart, bp, faces)
    spec = GeometrySpecification(Materials(_mixtures()), geometry, Eigen(CellCoefficient.every(Channel.FISSION_EMISSION)), exterior=exterior)
    with bypass():
        return float(CharacteristicDerivation(spec, Resolution(1, 0, 0.4, TransportResolution(8), 8)).evaluate(Eigenvalue()).value)


@pytest.mark.slow
@pytest.mark.rests_on(_HERE + "test_the_carry_fixture_is_the_population_it_claims", _WALLS + "test_walls_of_reads_what_head_read")
@pytest.mark.parametrize("name", _BODY_IDS)
def test_every_body_solves_to_the_head_bits(name: str) -> None:
    """The fundamental ``k`` of each re-posed body equals ``main`` ``5d04c296``'s, ``float.hex`` for ``float.hex``.

    ``rests_on`` the walls row: a body whose walls were read differently cannot be expected to solve identically, so a red here
    with that row green localises to the solve (the reference's use of the walls), and a red there bounds the cause. Population:
    19 bodies, 2 groups, 2 to 3 regions, 5 chart kinds. Red at base: the Sood registry import (``BC``)."""
    expected = _head()[name]["k_hex"]
    got = _k(name).hex()
    require(got == expected, f"{name}: k = {got}, HEAD {expected} (relative difference {abs(float.fromhex(got) / float.fromhex(expected) - 1.0):.3e})")


@pytest.mark.rests_on(_HERE + "test_the_carry_fixture_is_the_population_it_claims", _WALLS + "test_specular_albedos_reads_the_pair_geometry_and_exterior")
def test_the_specular_albedos_of_every_specular_only_body_are_head_s() -> None:
    """The 12 specular-only bodies' ``specular_albedos`` equal HEAD's list for them, in one sweep (the consumers' input).

    The per-body rows of ``test_walls_of_reads_decks_and_amplitudes.py`` localise a failure; this row is the population-level
    statement of the carry for the three consumers, with its count in the message. Red at base: the ``reference_body``
    import."""
    from orpheus.derivations.common.reference_body import specular_albedos

    head = _head()
    checked = 0
    for name, chart, bp, faces in cases.CASES:
        if name not in cases.SPECULAR_ONLY:
            continue
        geometry, exterior = spelling.geometry_and_exterior(chart, bp, faces)
        got = list(specular_albedos(geometry, exterior, owner="carry"))
        require(got == head[name]["albedos"], f"{name}: {got} against HEAD {head[name]['albedos']}")
        checked += 1
    require(checked == 12, f"checked {checked} bodies, not 12")
